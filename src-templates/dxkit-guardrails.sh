#!/usr/bin/env sh
#
# dxkit guardrails entry point: the one sequence of dxkit checks that a
# developer, an agent, the git hooks and the CI pipeline all run.
#
#   ./dxkit-guardrails.sh                  run what the pipeline runs
#   ./dxkit-guardrails.sh --quick          the pre-push tier
#   ./dxkit-guardrails.sh --changed-only   the pre-commit tier
#
# The checks, in this order:
#   1. findings guardrail    no net-new findings vs the baseline
#   2. policy-render parity  do the managed workflows match .dxkit/policy.json?
#   3. correctness floor     does the code still compile, do the tests pass?
# The guardrail and the parity check see the tree exactly as checked out; the
# floor runs the repo's own build and tests, which can write to the tree, so
# it runs last.
#
# Tiers:
#   (default)        Full-suite floor and full guardrail scan: what the CI
#                    workflow (dxkit-guardrails.yml) runs, so a clean run here
#                    means a clean run there. Every check runs even when an
#                    earlier one failed, so one run reports everything.
#   --quick          Floor scoped to the change (affected tests), guardrail
#                    scanned incrementally. Stops at the first failure. The
#                    pre-push hook runs this tier.
#   --changed-only   The guardrail only, blocking only on findings on lines
#                    you changed. The pre-commit hook runs this tier.
#   In --quick and --changed-only, a repo with no baseline file yet skips the
#   guardrail (not blocking) until `vyuh-dxkit baseline create` runs once.
#
# Pipeline options. The workflow passes these; pass them by hand to reproduce
# a specific pull request's run:
#   --base <branch>   The pull request's base branch. The floor attributes a
#                     failure against the merge-base (only a net-new failure
#                     blocks). When <branch> is not the default branch, the
#                     guardrail gates against origin/<branch> (ref-based),
#                     because the committed baseline is anchored to the
#                     default branch.
#   --untrusted       Analyze the tree as untrusted content (a fork's head):
#                     repo-declared plugins and check commands are disabled.
#   --report <file>   Write the markdown report (the pull request comment) to
#                     <file>: the guardrail verdict, then any policy drift,
#                     then any floor failure.
#
# Environment: DXKIT_BASELINE_NAME picks the baseline (default: main).
# DXKIT_FLOOR_CI, DXKIT_FLOOR_PREPUSH and DXKIT_FLOOR_TIMEOUT_MS tune the floor.
#
# Exit status: 0 when every check passed or was skipped for a stated reason;
# otherwise the exit status of the first check that failed; 2 on a usage
# error.
#
# Generated by dxkit; `vyuh-dxkit update` refreshes it. To change what the
# checks enforce, edit .dxkit/policy.json, not this file. POSIX sh on purpose:
# git hooks run under Git for Windows' sh too.

# Everything runs inside main(), which the shell reads in full before running
# it. `policy render --check` re-renders this very file and restores it, and a
# shell that reads a script as it goes would otherwise see that mid-run.

# Rendered at install as a single-quoted shell literal.
DEFAULT_BRANCH=__DXKIT_DEFAULT_BRANCH__

usage() {
  cat <<'EOF'
Usage: ./dxkit-guardrails.sh [--quick | --changed-only] [--base <branch>]
                             [--untrusted] [--report <file>]

Runs dxkit's checks in order: findings guardrail, policy-render parity,
correctness floor. With no options it runs what the CI pipeline runs.

  --quick          the pre-push tier (affected tests, incremental scan)
  --changed-only   the pre-commit tier (guardrail on changed lines only)
  --base <branch>  the pull request's base branch
  --untrusted      analyze the tree as untrusted content (a fork's head)
  --report <file>  write the markdown report (the PR comment) to <file>
EOF
}

say() {
  printf '[dxkit-guardrails] %s\n' "$*"
}

warn() {
  printf '[dxkit-guardrails] %s\n' "$*" >&2
}

in_actions() {
  [ "${GITHUB_ACTIONS:-}" = "true" ]
}

# An error line: a GitHub annotation inside Actions, plain stderr elsewhere.
report_error() {
  if in_actions; then
    printf '::error::%s\n' "$*"
  else
    warn "$*"
  fi
}

usage_error() {
  warn "$*"
  usage >&2
  exit 2
}

parse_args() {
  TIER=full
  BASE=""
  UNTRUSTED=""
  REPORT=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --quick | --changed-only)
        [ "$TIER" = full ] || usage_error "--quick and --changed-only are separate tiers; pass one."
        TIER=${1#--}
        ;;
      --base)
        [ $# -ge 2 ] || usage_error "--base needs a branch name."
        BASE=$2
        shift
        ;;
      --base=*) BASE=${1#--base=} ;;
      --untrusted) UNTRUSTED=--untrusted ;;
      --report)
        [ $# -ge 2 ] || usage_error "--report needs a file path."
        REPORT=$2
        shift
        ;;
      --report=*) REPORT=${1#--report=} ;;
      -h | --help)
        usage
        exit 0
        ;;
      *) usage_error "unknown option: $1" ;;
    esac
    shift
  done
  # The report path is the caller's, so resolve it before moving to the root.
  case "$REPORT" in
    "" | /*) ;;
    *) REPORT="$(pwd)/$REPORT" ;;
  esac
  if [ "$TIER" = full ]; then FAIL_FAST=0; else FAIL_FAST=1; fi
}

# The project-local install first, then a global one. Never npx: it may reach
# for the registry, which makes a hook slow and breaks it offline.
resolve_dxkit() {
  if [ -x ./node_modules/.bin/vyuh-dxkit ]; then
    DXKIT=./node_modules/.bin/vyuh-dxkit
  elif command -v vyuh-dxkit >/dev/null 2>&1; then
    DXKIT=vyuh-dxkit
  else
    warn "vyuh-dxkit not found on PATH or in ./node_modules/.bin."
    warn "  Install it with: npm install --save-dev __DXKIT_PACKAGE_SPEC__"
    warn "  From a git hook, skip it once with: DXKIT_SKIP_HOOKS=1 git <command> ..."
    return 1
  fi
}

make_workdir() {
  WORK=$(mktemp -d 2>/dev/null) || WORK=""
  if [ -z "$WORK" ]; then
    WORK="${TMPDIR:-/tmp}/dxkit-guardrails.$$"
    mkdir -p "$WORK" || exit 1
  fi
  trap 'rm -rf "$WORK"' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM
}

label() {
  case "$1" in
    floor) printf 'correctness floor' ;;
    parity) printf 'policy-render parity' ;;
    guardrail) printf 'findings guardrail' ;;
  esac
}

# record <check> <status> <exit code> <note>
# status: passed | failed | skipped | not-run | not-in-tier
FIRST_FAIL=0
FIRST_FAILED=""
record() {
  eval "R_$1_status=\$2; R_$1_code=\$3; R_$1_note=\$4"
  if [ "$2" = failed ] && [ "$FIRST_FAIL" -eq 0 ]; then
    FIRST_FAIL=$3
    FIRST_FAILED=$1
  fi
}

# In a fail-fast tier, a check after a failure does not run, and says so.
stopped_early() {
  if [ "$FAIL_FAST" -eq 1 ] && [ "$FIRST_FAIL" -ne 0 ]; then
    record "$1" not-run 0 "the $(label "$FIRST_FAILED") failed first, and the $TIER tier stops at the first failure (run ./dxkit-guardrails.sh for every check)"
    return 0
  fi
  return 1
}

check_floor() {
  if [ "$TIER" = changed-only ]; then
    record floor not-in-tier 0 "not part of the changed-only tier"
    return
  fi
  stopped_early floor && return
  say "3/3 $(label floor)"
  if [ "$TIER" = quick ]; then
    set -- floor check --surface pre-push
  else
    set -- floor check --surface ci
    if [ -n "$BASE" ]; then set -- "$@" --base "origin/$BASE"; fi
    if [ -n "$REPORT" ]; then set -- "$@" --report-md "$WORK/floor.md"; fi
  fi
  "$DXKIT" "$@"
  code=$?
  if [ "$code" -eq 0 ]; then record floor passed 0 ""; else record floor failed "$code" ""; fi
}

check_parity() {
  if [ "$TIER" = changed-only ]; then
    record parity not-in-tier 0 "not part of the changed-only tier"
    return
  fi
  stopped_early parity && return
  say "2/3 $(label parity)"
  # Snapshots the managed files, re-renders them from the policy, diffs, and
  # restores: the tree is untouched afterwards, and rendering executes nothing
  # from the repo, so this is safe on every pull request, forks included.
  "$DXKIT" policy render --check >"$WORK/parity.txt" 2>&1
  code=$?
  cat "$WORK/parity.txt"
  if [ "$code" -eq 0 ]; then
    record parity passed 0 ""
  else
    record parity failed "$code" ""
    report_error "policy drift: managed workflows do not match .dxkit/policy.json. Run 'npx vyuh-dxkit policy render --apply' and commit the result."
  fi
}

check_guardrail() {
  stopped_early guardrail && return
  say "1/3 $(label guardrail)"
  baseline_name=${DXKIT_BASELINE_NAME:-main}
  baseline_file=".dxkit/baselines/$baseline_name.json"
  set -- guardrail check --name "$baseline_name"
  if [ "$TIER" = full ]; then
    if [ -n "$BASE" ] && [ "$BASE" != "$DEFAULT_BRANCH" ]; then
      # A committed baseline is anchored to the default branch (its refresh
      # runs on pushes there), so diffing it against a change into another
      # base would read that base's own drift as this change's regressions.
      say "base '$BASE' is not the default branch '$DEFAULT_BRANCH': gating against origin/$BASE (ref-based), since the committed baseline is anchored to the default branch."
      set -- "$@" --mode ref-based --ref "origin/$BASE"
    elif [ ! -f "$baseline_file" ] &&
      [ "$("$DXKIT" policy get baseline.anchor --default tree 2>/dev/null)" = cache ]; then
      # The cache transport keeps the anchor in the CI cache, never in the
      # tree: a cold cache in CI, or any local run, has no anchor file.
      say "cache transport with no baseline anchor here (a cache miss, or a local run): gating against origin/${BASE:-$DEFAULT_BRANCH} (ref-based) for this run."
      set -- "$@" --mode ref-based --ref "origin/${BASE:-$DEFAULT_BRANCH}"
    fi
  else
    if [ ! -f "$baseline_file" ]; then
      say "No baseline at $baseline_file, so the guardrail is not blocking."
      say "  Run \`$DXKIT baseline create\` once to start gating."
      record guardrail skipped 0 "no baseline at $baseline_file yet (run baseline create once)"
      return
    fi
    if [ "$TIER" = quick ]; then
      set -- "$@" --incremental
    else
      set -- "$@" --changed-only
    fi
  fi
  if [ -n "$UNTRUSTED" ]; then set -- "$@" --untrusted; fi

  if [ -z "$REPORT" ]; then
    "$DXKIT" "$@"
    code=$?
  else
    "$DXKIT" "$@" --markdown >"$WORK/guardrail.md"
    code=$?
    if [ "$code" -ne 0 ]; then
      # Say why in the log itself, not only in the report.
      if in_actions; then echo "::group::dxkit guardrail BLOCKED: net-new findings vs the baseline"; fi
      cat "$WORK/guardrail.md"
      if in_actions; then echo "::endgroup::"; fi
    fi
  fi
  if [ "$code" -eq 0 ]; then
    record guardrail passed 0 ""
  else
    record guardrail failed "$code" ""
    report_error "dxkit guardrail blocked: this change introduced net-new findings vs the baseline${REPORT:+ (full report above and in the PR comment)}."
  fi
}

describe_result() {
  eval "st=\$R_$1_status; rc=\$R_$1_code; note=\$R_$1_note"
  case "$st" in
    passed) printf 'passed' ;;
    failed) printf 'FAILED (exit %s)' "$rc" ;;
    skipped) printf 'skipped: %s' "$note" ;;
    not-run) printf 'did not run: %s' "$note" ;;
    not-in-tier) printf '%s' "$note" ;;
  esac
}

# The pull request comment: the guardrail verdict leads (the comment is cut
# from the bottom when it is too long), then policy drift, then the floor's
# disclosure. A check that did not produce its section says why.
write_report() {
  [ -n "$REPORT" ] || return 0
  {
    if [ -s "$WORK/guardrail.md" ]; then
      cat "$WORK/guardrail.md"
    elif [ "$R_guardrail_status" = failed ]; then
      printf '### dxkit guardrail: FAILED (exit %s) without a report\n\nSee this run'"'"'s log.\n' "$R_guardrail_code"
    else
      printf '### dxkit guardrail: %s\n' "$(describe_result guardrail)"
    fi
    if [ "$R_parity_status" = failed ]; then
      printf '\n\n### Policy drift: managed workflows do not match .dxkit/policy.json\n\n'
      printf 'A policy change is landing without the re-render of the workflows it gates. '
      printf 'Run `npx vyuh-dxkit policy render --apply` and commit the result:\n\n'
      printf '```diff\n'
      cat "$WORK/parity.txt"
      printf '\n```\n'
    elif [ "$R_parity_status" = not-run ]; then
      printf '\n\n### Policy-render parity: %s\n' "$(describe_result parity)"
    fi
    if [ -s "$WORK/floor.md" ]; then
      cat "$WORK/floor.md"
    elif [ "$R_floor_status" = not-run ]; then
      printf '\n\n### Correctness floor: %s\n' "$(describe_result floor)"
    fi
  } >"$WORK/report.md" || return 1
  # One checked copy: the group's own status is its last command's, which
  # would hide a failed write earlier in it.
  cat "$WORK/report.md" >"$REPORT"
}

summarize() {
  echo
  say "$TIER tier:"
  for c in guardrail parity floor; do
    printf '  %-22s %s\n' "$(label "$c")" "$(describe_result "$c")"
  done
  if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
    {
      printf '\n### dxkit guardrails (%s tier)\n\n| Check | Result |\n| --- | --- |\n' "$TIER"
      for c in guardrail parity floor; do
        printf '| %s | %s |\n' "$(label "$c")" "$(describe_result "$c")"
      done
    } >>"$GITHUB_STEP_SUMMARY" 2>/dev/null || true
  fi
}

main() {
  parse_args "$@"
  # The script sits at the repo root; run from there whatever the caller's cwd.
  cd "$(dirname "$0")" || exit 1
  resolve_dxkit || exit 1
  make_workdir
  if [ "$TIER" = changed-only ]; then
    say "running the changed-only tier: $(label guardrail), changed lines only"
  else
    say "running the $TIER tier: $(label guardrail), $(label parity), $(label floor)"
  fi
  check_guardrail
  check_parity
  check_floor
  if ! write_report; then
    report_error "could not write the report to $REPORT, so the pull request comment cannot show this run."
    if [ "$FIRST_FAIL" -eq 0 ]; then FIRST_FAIL=1; fi
  fi
  summarize
  exit "$FIRST_FAIL"
}

main "$@"; exit $?
