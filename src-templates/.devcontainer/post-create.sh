#!/usr/bin/env bash
#
# Devcontainer post-create. Runs once after the container is built
# (and again on Codespaces prebuild). Idempotent: safe to re-run.
# Generated and refreshed by dxkit (`vyuh-dxkit update` re-renders it).
#
# Steps:
#   1. Install the project's dependencies the way CI installs them.
#   2. Resolve dxkit: the project's own devDependency first, else a
#      global install of the exact dxkit version that generated this
#      file. A global dxkit at any other version is replaced, not reused.
#   3. Install dxkit's scanner toolchain (pinned in dxkit's registry).
#   4. Activate dxkit's git hooks when the repo carries them.
#   5. Install the AI coding-agent CLIs at their pinned versions.
#
# Readiness is reported honestly: every step runs, each failure is
# recorded with its reason and remedy, one summary is printed at the
# end, and the script exits non-zero when the environment is not ready.
# The devcontainer UI and an agent runner therefore see a failed
# post-create instead of a green one. The outcome is also written to
# __DXKIT_READINESS_RECORD__ (read by `vyuh-dxkit doctor`).
#
# Run from the repo root: the devcontainer's workspaceFolder is set by
# devcontainer.json, so the post-create command starts there.

set -uo pipefail

# The dxkit release that generated this file.
DXKIT_VERSION="__DXKIT_VERSION__"
DXKIT_PACKAGE="__DXKIT_PACKAGE__"
READINESS_RECORD="__DXKIT_READINESS_RECORD__"

FAILURES=()
DXKIT=""
DXKIT_RESOLVED=""

# fail_step <step> <reason> <remedy>
fail_step() {
  FAILURES+=("$1"$'\t'"$2"$'\t'"$3")
  echo "FAIL [$1]: $2" >&2
}

# The first x.y.z a CLI's `--version` prints, or empty when it does not run.
version_of() {
  "$1" --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n1
}

echo "==> dxkit post-create (generated by dxkit ${DXKIT_VERSION}) starting in $(pwd)"

# ── 1. Project dependencies ────────────────────────────────────────────
# The same install chain the generated CI workflows run (rendered from
# dxkit's install strategies under this repo's authorized tolerances), so
# the container holds the tree the repo ships and CI audits. A tree that
# only re-resolves under a looser install is not ready: re-sync the
# lockfile instead. A private registry needs its auth configured first.
if [ -f package.json ]; then
  echo "==> Installing project dependencies (the install CI runs)..."
  if (
    __DXKIT_INSTALL_DEPS__
  ); then
    echo "    dependencies installed"
  else
    cls=""
    if [ -f "__DXKIT_INSTALL_RECORD__" ]; then
      cls="$(node -e 'try{const r=require(process.argv[1]);process.stdout.write(String(r.class||""))}catch{}' "$(pwd)/__DXKIT_INSTALL_RECORD__" 2>/dev/null || true)"
    fi
    fail_step "project dependencies" \
      "the dependency install failed${cls:+ (${cls})}; output in __DXKIT_INSTALL_LOG__" \
      "fix the cause shown above (lockfile drift: re-sync and commit the lockfile; a private registry: configure its auth, e.g. an .npmrc token from the container's secrets), then re-run 'bash .devcontainer/post-create.sh'"
  fi
fi

# ── 2. dxkit ───────────────────────────────────────────────────────────
# The project's devDependency is the version the repo's hooks and CI run,
# so it is preferred and linked onto PATH for terminals and agents. With
# no devDependency, dxkit is installed globally at exactly the version
# that generated this file; whatever else is on PATH is replaced.
echo "==> Resolving dxkit..."
if [ -x ./node_modules/.bin/vyuh-dxkit ]; then
  local_version="$(version_of ./node_modules/.bin/vyuh-dxkit)"
  if [ -z "${local_version}" ]; then
    fail_step "dxkit" \
      "the project's dxkit devDependency is installed but does not run" \
      "re-install the project's dependencies, then re-run 'bash .devcontainer/post-create.sh'"
  else
    DXKIT="./node_modules/.bin/vyuh-dxkit"
    DXKIT_RESOLVED="${local_version}"
    echo "    project devDependency: dxkit ${local_version}"
    if [ "${local_version}" != "${DXKIT_VERSION}" ]; then
      echo "    note: these files were generated by dxkit ${DXKIT_VERSION}; run 'vyuh-dxkit update' to regenerate them with ${local_version}."
    fi
    global_bin="$(npm prefix -g 2>/dev/null)/bin"
    if ln -sf "$(pwd)/node_modules/.bin/vyuh-dxkit" "${global_bin}/vyuh-dxkit" 2>/dev/null; then
      hash -r
    fi
    on_path="$(command -v vyuh-dxkit >/dev/null 2>&1 && version_of vyuh-dxkit || true)"
    if [ "${on_path}" != "${local_version}" ]; then
      fail_step "dxkit on PATH" \
        "'vyuh-dxkit' in a shell resolves to ${on_path:-nothing}, not the project's ${local_version}" \
        "remove the other vyuh-dxkit from PATH, or link node_modules/.bin/vyuh-dxkit into a PATH directory"
    fi
  fi
else
  global_version="$(command -v vyuh-dxkit >/dev/null 2>&1 && version_of vyuh-dxkit || true)"
  if [ "${global_version}" != "${DXKIT_VERSION}" ]; then
    if [ -n "${global_version}" ]; then
      echo "    global dxkit is ${global_version}; installing the pinned ${DXKIT_VERSION}"
    fi
    npm install -g "${DXKIT_PACKAGE}@${DXKIT_VERSION}" || true
    hash -r
    global_version="$(command -v vyuh-dxkit >/dev/null 2>&1 && version_of vyuh-dxkit || true)"
  fi
  if [ "${global_version}" = "${DXKIT_VERSION}" ]; then
    DXKIT="vyuh-dxkit"
    DXKIT_RESOLVED="${global_version}"
    echo "    global: dxkit ${global_version}"
  else
    fail_step "dxkit" \
      "dxkit ${DXKIT_VERSION} is not on PATH (found: ${global_version:-nothing})" \
      "run 'npm install -g ${DXKIT_PACKAGE}@${DXKIT_VERSION}' (check registry access), or add ${DXKIT_PACKAGE} as a devDependency"
  fi
fi

# ── 3. Scanner toolchain ───────────────────────────────────────────────
# `--fail-on-missing`: exit non-zero when a required scanner is still
# missing afterwards. Optional tools never fail the environment.
echo "==> Installing scanner toolchain via dxkit registry..."
if [ -z "${DXKIT}" ]; then
  fail_step "scanner toolchain" "not installed: no runnable dxkit (see the dxkit step)" \
    "fix the dxkit step, then re-run 'bash .devcontainer/post-create.sh'"
elif ! "${DXKIT}" tools install --yes --fail-on-missing; then
  fail_step "scanner toolchain" "a required scanner did not install (see the tools summary above)" \
    "run 'vyuh-dxkit tools install --yes' and fix the cause it reports"
fi

# ── 4. Git hooks ───────────────────────────────────────────────────────
# `core.hooksPath` lives in .git/config, which a fresh clone (Codespaces,
# an agent runner) does not carry, and the package.json postinstall that
# re-applies it exists only on Node repos. Activate it here; a hook that
# is present but not active means pushes skip the guardrail.
if [ -f .githooks/pre-push ]; then
  echo "==> Activating dxkit git hooks..."
  if [ -n "${DXKIT}" ]; then
    "${DXKIT}" hooks activate || true
  fi
  hooks_path="$(git config --local --get core.hooksPath 2>/dev/null || true)"
  if [ "${hooks_path}" = ".githooks" ]; then
    echo "    pre-push guardrail active (core.hooksPath = .githooks)"
  elif [ -n "${hooks_path}" ] &&
    grep -qsE 'githooks/pre-push|vyuh-dxkit' "${hooks_path}/pre-push" "$(dirname "${hooks_path}")/pre-push"; then
    echo "    pre-push guardrail chained from ${hooks_path}"
  else
    fail_step "git hooks" \
      "dxkit's pre-push guardrail is present but not active (core.hooksPath = ${hooks_path:-unset})" \
      "run 'vyuh-dxkit hooks activate'; if core.hooksPath points at another hook manager, call .githooks/pre-push from its pre-push hook"
  fi
fi

# ── 5. AI coding-agent CLIs ────────────────────────────────────────────
echo "==> Installing AI coding-agent CLIs..."
if ! bash "$(dirname "$0")/install-agent-clis.sh"; then
  fail_step "agent CLIs" "a coding-agent CLI is not installed at its pinned version (see above)" \
    "fix the cause above and re-run 'bash .devcontainer/install-agent-clis.sh', or set CLAUDE_CODE_VERSION / CODEX_VERSION to 'skip' for a CLI you do not use"
fi

# ── Readiness ──────────────────────────────────────────────────────────
mkdir -p "$(dirname "${READINESS_RECORD}")" 2>/dev/null
DXKIT_RECORD_PATH="${READINESS_RECORD}" \
  DXKIT_RECORD_VERSION="${DXKIT_VERSION}" \
  DXKIT_RECORD_RESOLVED="${DXKIT_RESOLVED}" \
  DXKIT_RECORD_FAILURES="$(printf '%s\n' ${FAILURES[@]+"${FAILURES[@]}"})" \
  node -e '
const fs = require("fs");
const e = process.env;
const failures = (e.DXKIT_RECORD_FAILURES || "").split("\n").filter(Boolean).map((line) => {
  const [step, reason, remedy] = line.split("\t");
  return { step, reason, remedy };
});
fs.writeFileSync(e.DXKIT_RECORD_PATH, JSON.stringify({
  schema: "dxkit.devcontainer-readiness.v1",
  ready: failures.length === 0,
  generatedBy: e.DXKIT_RECORD_VERSION,
  dxkit: e.DXKIT_RECORD_RESOLVED || null,
  finishedAt: new Date().toISOString(),
  failures,
}, null, 2) + "\n");
' 2>/dev/null || echo "note: could not write the readiness record ${READINESS_RECORD}" >&2

echo
if [ "${#FAILURES[@]}" -eq 0 ]; then
  echo "==> dxkit post-create: environment READY (dxkit ${DXKIT_RESOLVED})."
  exit 0
fi
echo "==> dxkit post-create: environment NOT READY (${#FAILURES[@]} step(s) failed):" >&2
for entry in "${FAILURES[@]}"; do
  IFS=$'\t' read -r step reason remedy <<<"${entry}"
  echo "  x ${step}: ${reason}" >&2
  echo "    remedy: ${remedy}" >&2
done
echo "  Re-run after fixing: bash .devcontainer/post-create.sh" >&2
exit 1
